const categoryOrder=['Web Design','Jewellery','Branding','Print Design','Packaging','Social Media','Paid Ads','Festival & Greetings'];
const workSections=document.getElementById('workSections'),workFilters=document.getElementById('workFilters'),workViewer=document.getElementById('workViewer');
let lastWorkButton=null;
function renderWork(category='All work'){
 workFilters.querySelectorAll('button').forEach(b=>{const active=b.dataset.category===category;b.classList.toggle('active',active);b.setAttribute('aria-pressed',String(active))});
 const items=projects.filter(p=>category==='All work'||p.category===category);
 document.getElementById('workCount').textContent=items.length+' designs · '+category;
 workSections.replaceChildren();
 categoryOrder.filter(c=>category==='All work'||c===category).forEach((c,index)=>{
  const entries=items.filter(p=>p.category===c);if(!entries.length)return;
  const section=document.createElement('section');section.className='work-category';section.setAttribute('aria-labelledby','work-category-'+index);
  const heading=document.createElement('div');heading.className='work-category-heading';
  const title=document.createElement('h3');title.id='work-category-'+index;title.textContent=c;
  const count=document.createElement('span');count.textContent=entries.length+' designs';heading.append(title,count);
  const grid=document.createElement('div');grid.className='work-grid';section.append(heading,grid);
  entries.forEach(p=>{
   const article=document.createElement('article');article.className='work-card';
   const button=document.createElement('button');button.type='button';button.className='work-thumb'+(p.longImage?' work-tall':'');button.setAttribute('aria-label','View '+p.title);
   const image=document.createElement('img');image.src=p.image;image.alt=p.title;image.loading='lazy';image.decoding='async';
   const arrow=document.createElement('span');arrow.className='work-arrow';arrow.textContent='↗';arrow.setAttribute('aria-hidden','true');button.append(image,arrow);
   button.addEventListener('click',()=>{lastWorkButton=button;document.getElementById('workViewerTitle').textContent=p.title;const full=document.getElementById('workViewerImage');full.src=p.image;full.alt=p.title;workViewer.classList.toggle('work-viewer-tall',Boolean(p.longImage));workViewer.showModal();workViewer.scrollTop=0});
   const name=document.createElement('h4');name.textContent=p.title;const description=document.createElement('p');description.textContent=p.description;article.append(button,name,description);grid.append(article);
  });
  workSections.append(section);
 });
}
['All work',...categoryOrder].forEach(category=>{const button=document.createElement('button');button.type='button';button.className='filter-btn';button.dataset.category=category;button.textContent=category;button.addEventListener('click',()=>renderWork(category));workFilters.append(button)});
document.getElementById('workClose').addEventListener('click',()=>workViewer.close());
workViewer.addEventListener('close',()=>lastWorkButton?.focus());
workViewer.addEventListener('click',event=>{if(event.target!==workViewer)return;const r=workViewer.getBoundingClientRect();if(event.clientX<r.left||event.clientX>r.right||event.clientY<r.top||event.clientY>r.bottom)workViewer.close()});
renderWork();
